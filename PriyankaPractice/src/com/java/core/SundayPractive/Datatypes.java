package com.java.core.SundayPractive;

public class Datatypes {

	
	public static void main(String[] args) {
		
		System.out.println("Datatypes");
		
		int a = 20; 
	System.out.println("int = " +a);
		
		short age = 28;
		System.out.println("Short = " +age);
		
		long phonenumber = 456123478;
		System.out.println("Long = " +phonenumber);
		
		double percentage = 82.83;
		System.out.println("Double = " +percentage);
		
		float average = 56.25f;
		System.out.println("Average" +average);
		
		char Alphabet = 'P';
		System.out.println("Char = " +Alphabet);
		
		byte MB = 12;
		System.out.println("byte = " +MB);
		
		boolean IsMarried = true;
		System.out.println("boolean = " +IsMarried);
		
		System.out.println("----------------------------------------");
		
		System.out.println("Operators");
		
		int b = 20;
		int c = 20;
		
		int add = a+b;
		
		System.out.println("Addition = " +add);
		
		int d = 20;
		int e = 10;
		
		int sub = d-e;
		
		System.out.println("Subs = " +sub);
		
		int f = 50;
		int g = 4;
		
		int mul = f*g;
		
	System.out.println("mul" +mul);
		
		int h = 80;
		int i = 4;
		
		int div = h/i;
		
		System.out.println("Div =" +div);
		
		int j = 50;
		int k = 4;
		
		int mod = j%4;
		
		System.out.println("Mod = " +mod);
		
		System.out.println("----------------------------------------");
		
		System.out.println("Casting");
		
		int y = 40;
		int r = 50;
		
		double mult = y*r;
		System.out.println("Implicit casting = " +mult);
		

		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
		
	}
}
